#!/usr/bin/env python3
"""Generate credits; prose and translations belong to the shared UI catalog."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

from yume_translations import message_symbol

ROOT = Path(__file__).resolve().parents[1]
ANDROID_OUTPUT = Path('app/src/main/java/com/fixcraft/yume/ui/settings/GeneratedCredits.kt')
GROUPS = ('native', 'linux', 'desktop', 'android', 'mlkit')


def load(path: Path = ROOT / 'config/credits.json',
         catalog_path: Path = ROOT / 'translations/catalog.json') -> tuple[dict, dict]:
    data = json.loads(path.read_text(encoding='utf-8'))
    catalog = json.loads(catalog_path.read_text(encoding='utf-8'))
    messages = {m['id']: m['source'] for m in catalog['messages']}
    if set(data) != {'schema', 'contributors', 'components'} or type(data['schema']) is not int or data['schema'] != 1:
        raise ValueError('credits must have schema 1, contributors and components')
    if not isinstance(data['components'], dict) or set(data['components']) != set(GROUPS):
        raise ValueError('credits component groups must be ' + ', '.join(GROUPS))
    groups = [('contributors', data['contributors'], {'name', 'role', 'contribution'}, ('role', 'contribution'))]
    groups.extend((name, data['components'][name], {'name', 'license', 'use'}, ('use',)) for name in GROUPS)
    for name, rows, fields, ids in groups:
        if not isinstance(rows, list) or not rows:
            raise ValueError(f'{name} must be a nonempty list')
        names = set()
        for row in rows:
            if not isinstance(row, dict) or set(row) != fields:
                raise ValueError(f'{name}: expected fields {sorted(fields)}')
            if any(not isinstance(v, str) or not v.strip() or any(ord(c) < 32 for c in v) for v in row.values()):
                raise ValueError(f'{name}: fields must be nonempty single-line strings')
            if row['name'] in names:
                raise ValueError(f'{name}: duplicate {row["name"]}')
            names.add(row['name'])
            for key in ids:
                if row[key] not in messages:
                    raise ValueError(f'{name}: unknown catalog ID {row[key]}')
    return data, messages


def literal(value: str, *, kotlin: bool = False) -> str:
    # JSON's quoted UTF-8 string is also a C++ string; Kotlin additionally
    # interpolates dollar signs even in ordinary quoted strings.
    result = json.dumps(value, ensure_ascii=False)
    return result.replace('$', r'\$') if kotlin else result


def render(data: dict, messages: dict, root: Path,
           android_root: Path | None = None) -> dict[Path, str]:
    def resolved(row: dict) -> dict:
        return {key: messages[value] if key in ('role', 'contribution', 'use') else value
                for key, value in row.items()}

    people = [resolved(row) for row in data['contributors']]
    components = {group: [resolved(row) for row in rows] for group, rows in data['components'].items()}
    outputs = {root / 'website/_data/credits.json': json.dumps(
        {'schema': 1, 'contributors': people, 'components': components}, ensure_ascii=False, indent=2) + '\n'}
    lines = ['// Generated by scripts/yume_credits.py. Do not edit.', '#pragma once',
             'namespace yume::credits {',
             'struct Person { const char* name; const char* role; const char* contribution; };',
             'inline constexpr Person kPeople[] = {']
    lines.extend('    {' + ', '.join(literal(row[k]) for k in ('name', 'role', 'contribution')) + '},' for row in people)
    lines += ['};', 'struct Component { const char* name; const char* license; const char* use; };',
              'inline constexpr Component kNativeComponents[] = {']
    lines.extend('    {' + ', '.join(literal(row[k]) for k in ('name', 'license', 'use')) + '},'
                 for row in components['native'] + components['linux'])
    lines += ['};', '}  // namespace yume::credits', '']
    outputs[root / 'src/runtime/credits.hpp'] = '\n'.join(lines)
    if android_root is not None:
        lines = ['// Generated by scripts/yume_credits.py. Do not edit.',
                 'package com.fixcraft.yume.ui.settings', '',
                 'import com.fixcraft.yume.i18n.MessageId', '',
                 'internal data class SharedCredit(val name: String, val role: MessageId, val contribution: MessageId)',
                 'internal data class SharedComponent(val name: String, val license: String, val use: MessageId)',
                 'internal object GeneratedCredits {', '    val contributors = listOf(']
        for row in data['contributors']:
            lines.append(f'        SharedCredit({literal(row["name"], kotlin=True)}, MessageId.{message_symbol(row["role"])}, MessageId.{message_symbol(row["contribution"])}),')
        lines += ['    )']
        for group in ('native', 'android', 'mlkit'):
            lines.append(f'    val {group}Components = listOf(')
            for row in data['components'][group]:
                lines.append(f'        SharedComponent({literal(row["name"], kotlin=True)}, {literal(row["license"], kotlin=True)}, MessageId.{message_symbol(row["use"])}),')
            lines.append('    )')
        lines += ['}', '']
        outputs[android_root / ANDROID_OUTPUT] = '\n'.join(lines)
    return outputs


def generate(outputs: dict[Path, str], *, check: bool = False) -> list[Path]:
    changed = [path for path, content in outputs.items()
               if not path.is_file() or path.read_text(encoding='utf-8') != content]
    if not check:
        for path in changed:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(outputs[path], encoding='utf-8')
    return changed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=('validate', 'generate'))
    parser.add_argument('--check', action='store_true', help='fail on drift without writing')
    parser.add_argument('--android-root', type=Path, help='separate Android checkout to generate/check')
    args = parser.parse_args()
    if args.check and args.command != 'generate':
        parser.error('--check requires generate')
    try:
        data, messages = load()
        if args.android_root is not None and not (args.android_root / 'app').is_dir():
            raise ValueError('--android-root must contain app/')
        if args.command == 'generate':
            changed = generate(render(data, messages, ROOT, args.android_root), check=args.check)
            if args.check and changed:
                for path in changed:
                    print(f'credits drift: {path}', file=sys.stderr)
                return 1
        print('credits: valid' + ('; Android not requested' if args.android_root is None else '; Android included'))
        return 0
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f'credits: {error}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
