#!/usr/bin/env python3
"""Validate YUME's colour palette and generate each consumer's view of it.

config/palette.json is the one calibrated source: light, dark and their
variants as OKLCH values on the mark's hue, the role colours of figures and
states, and the contrast every theme must keep. The desktop GUI's
src/gui/qml/Palette.js, the colour section of website/assets/tokens.css and
the Android app's GeneratedPalette.kt, and the mark colours of the desktop's
tray icon in src/gui/palette.hpp are generated from it. The mark keeps its
shape in src/gui/assets/icon.svg, the original drawing. Its translucent
gradient is made for white, so every generated mark fills that shape with the
solid colours it shows over white: the website's yume-mark.svg and the
Android launcher icon, whose tile is the palette's light surface. The README
banner combines that shape and these colours with the outlined lettering and
layout in docs/assets/readme-banner.svg.in. A new consumer, such as an iOS
app, adds one renderer here.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
import re
from string import Template
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path('config/palette.json')
QML_OUTPUT = Path('src/gui/qml/Palette.js')
WEB_OUTPUT = Path('website/assets/tokens.css')
CPP_OUTPUT = Path('src/gui/palette.hpp')
MARK_SOURCE = Path('src/gui/assets/icon.svg')
WEB_MARK_OUTPUT = Path('website/assets/yume-mark.svg')
README_BANNER_SOURCE = Path('docs/assets/readme-banner.svg.in')
README_BANNER_OUTPUT = Path('docs/assets/readme-banner.svg')
ANDROID_MARK_OUTPUT = Path('app/src/main/res/drawable/ic_launcher_foreground.xml')
ANDROID_TILE_OUTPUT = Path('app/src/main/res/values/ic_launcher_background.xml')
ANDROID_OUTPUT = Path('app/src/main/java/com/fixcraft/yume/ui/theme/GeneratedPalette.kt')
BANNER = 'Generated by scripts/yume_palette.py from config/palette.json. Do not edit.'

THEMES = ('light', 'dark')
TOKENS = (
    'page', 'surface', 'raised', 'hover', 'ink', 'inkSoft', 'muted', 'lineStrong', 'line', 'hairline',
    'accent', 'accentMid', 'accentOn', 'accentSoft', 'accentInk', 'tonal', 'tonalInk',
    'button', 'buttonHover', 'buttonPressed', 'buttonInk', 'focus', 'track', 'inverse', 'inverseInk', 'inverseAccent',
    'logoFrom', 'logoTo', 'code', 'codeHead', 'codeInk', 'codeRule', 'codeInline',
)
TONES = ('mid', 'strong', 'soft', 'onSoft', 'dot')
HEX = re.compile(r'#[0-9A-F]{6}')

# Material 3 roles for Android, each named by a token or a role tone. Cards,
# dialogs and the bars are the surface, rows inside them are raised, and the
# page sits below both in either theme.
MATERIAL = {
    'primary': 'accent', 'onPrimary': 'accentOn', 'primaryContainer': 'accentSoft',
    'onPrimaryContainer': 'accentInk', 'inversePrimary': 'inverseAccent',
    'secondary': 'inkSoft', 'onSecondary': 'page', 'secondaryContainer': 'tonal',
    'onSecondaryContainer': 'tonalInk',
    'tertiary': 'server.strong', 'onTertiary': 'page', 'tertiaryContainer': 'server.soft',
    'onTertiaryContainer': 'server.onSoft',
    'background': 'page', 'onBackground': 'ink', 'surface': 'page', 'onSurface': 'ink',
    'surfaceVariant': 'raised', 'onSurfaceVariant': 'inkSoft', 'surfaceTint': 'accent',
    'inverseSurface': 'inverse', 'inverseOnSurface': 'inverseInk',
    'error': 'refused.strong', 'onError': 'page', 'errorContainer': 'refused.soft',
    'onErrorContainer': 'refused.onSoft',
    'outline': 'lineStrong', 'outlineVariant': 'hairline', 'scrim': '#000000',
    'surfaceBright': 'surface', 'surfaceDim': 'page', 'surfaceContainerLowest': 'page',
    'surfaceContainerLow': 'surface', 'surfaceContainer': 'surface', 'surfaceContainerHigh': 'surface',
    'surfaceContainerHighest': 'raised',
}

# The website's token names. Literal values are generated, references stay.
WEB = (
    ('paper', 'page'), ('paper-soft', 'hover'), ('paper-deep', 'raised'), ('cloud', 'surface'),
    ('ink', 'ink'), ('ink-soft', 'inkSoft'), ('muted', 'muted'),
    ('rule', 'line'), ('rule-soft', 'hairline'), ('line-strong', 'lineStrong'),
    ('logo-from', 'logoFrom'), ('logo-to', 'logoTo'),
    ('accent', 'accentMid'), ('accent-strong', 'accent'), ('accent-soft', 'accentSoft'), ('accent-ink', 'accentInk'),
    ('button', 'button'), ('button-hover', 'buttonHover'), ('button-pressed', 'buttonPressed'),
    ('button-ink', 'buttonInk'), ('focus', 'focus'), ('track', 'track'),
    ('code', 'code'), ('code-head', 'codeHead'), ('code-ink', 'codeInk'), ('code-rule', 'codeRule'),
    ('code-inline', 'codeInline'), ('warn', 'disguise.strong'), ('warn-soft', 'disguise.soft'),
)
WEB_REFERENCES = (
    ('role-client', 'var(--color-accent)'), ('role-client-strong', 'var(--color-accent-strong)'),
    ('role-client-soft', 'var(--color-accent-soft)'), ('role-neutral', 'var(--color-rule)'),
    ('role-neutral-strong', 'var(--color-muted)'), ('role-neutral-soft', 'var(--color-rule-soft)'),
)
WEB_TONES = (('', 'mid'), ('-strong', 'strong'), ('-soft', 'soft'), ('-ink', 'onSoft'))


def oklab_to_srgb(lightness: float, chroma: float, hue: float) -> tuple[float, float, float]:
    a = chroma * math.cos(math.radians(hue))
    b = chroma * math.sin(math.radians(hue))
    l_ = (lightness + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m_ = (lightness - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s_ = (lightness - 0.0894841775 * a - 1.2914855480 * b) ** 3
    linear = (4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
              -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
              -0.0041960863 * l_ - 0.7034186147 * m_ + 1.7076147010 * s_)

    def encode(channel: float) -> float:
        channel = min(max(channel, 0.0), 1.0)
        return 12.92 * channel if channel <= 0.0031308 else 1.055 * channel ** (1 / 2.4) - 0.055
    return tuple(encode(channel) for channel in linear)


class Colour:
    """One value: an OKLCH triple, or an exact sRGB hex for white and black."""

    def __init__(self, value, hue: float, where: str) -> None:
        if isinstance(value, str):
            if not HEX.fullmatch(value):
                raise ValueError(f'{where}: a string value must be #RRGGBB in upper case')
            self.oklch = None
            self.hex = value
            return
        if not isinstance(value, list) or len(value) not in (2, 3) or \
                any(type(part) not in (int, float) for part in value):
            raise ValueError(f'{where}: expected [lightness, chroma] or [lightness, chroma, hue]')
        lightness, chroma = float(value[0]), float(value[1])
        own_hue = float(value[2]) if len(value) == 3 else hue
        if not 0 <= lightness <= 1 or not 0 <= chroma <= 0.37 or not 0 <= own_hue < 360:
            raise ValueError(f'{where}: OKLCH out of range')
        self.oklch = (lightness, chroma, own_hue)
        self.hex = '#%02X%02X%02X' % tuple(round(c * 255) for c in oklab_to_srgb(*self.oklch))

    def css(self) -> str:
        if self.oklch is None:
            return self.hex
        lightness, chroma, hue = self.oklch
        return f'oklch({lightness * 100:g}% {chroma:g} {hue:g})'


def luminance(value: str) -> float:
    channels = [int(value[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    channels = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * channels[0] + 0.7152 * channels[1] + 0.0722 * channels[2]


def contrast(first: str, second: str) -> float:
    high, low = sorted((luminance(first), luminance(second)), reverse=True)
    return (high + 0.05) / (low + 0.05)


def load(path: Path = ROOT / SOURCE) -> dict:
    """The palette resolved to every theme, after checking its shape and contrast."""
    data = json.loads(path.read_text(encoding='utf-8'))
    if set(data) != {'schema', 'hue', 'themes', 'variants', 'roles', 'roleTones', 'contrast'} or \
            type(data['schema']) is not int or data['schema'] != 1:
        raise ValueError('palette must have schema 1, hue, themes, variants, roles, roleTones and contrast')
    hue = data['hue']
    if type(hue) not in (int, float) or not 0 <= hue < 360:
        raise ValueError('hue must be a number from 0 to 359')
    if set(data['themes']) != set(THEMES):
        raise ValueError('themes must be ' + ', '.join(THEMES))
    roles = data['roles']
    if not isinstance(roles, dict) or not roles or \
            any(not re.fullmatch(r'[a-z]+', name) or type(h) not in (int, float) or not 0 <= h < 360
                for name, h in roles.items()):
        raise ValueError('roles map lower-case names to hues')
    if set(data['roleTones']) != set(THEMES) or any(set(t) != set(TONES) for t in data['roleTones'].values()):
        raise ValueError('roleTones must give ' + ', '.join(TONES) + ' for each theme')

    def theme(name: str, tokens: dict, tones: dict) -> dict:
        if set(tokens) != set(TOKENS):
            missing, extra = set(TOKENS) - set(tokens), set(tokens) - set(TOKENS)
            raise ValueError(f'{name}: missing {sorted(missing)}, unknown {sorted(extra)}')
        resolved = {token: Colour(tokens[token], hue, f'{name}.{token}') for token in TOKENS}
        for role, role_hue in roles.items():
            for tone in TONES:
                resolved[f'{role}.{tone}'] = Colour(tones[tone][:2] + [role_hue], hue, f'{name}.{role}.{tone}')
        return resolved

    themes = {name: theme(name, data['themes'][name], data['roleTones'][name]) for name in THEMES}
    for name, variant in data['variants'].items():
        if not isinstance(variant, dict) or set(variant) != {'base', 'tokens'} or variant['base'] not in THEMES:
            raise ValueError(f'variant {name}: needs base (light or dark) and tokens')
        unknown = set(variant['tokens']) - set(TOKENS)
        if unknown:
            raise ValueError(f'variant {name}: unknown tokens {sorted(unknown)}')
        tokens = dict(data['themes'][variant['base']])
        tokens.update(variant['tokens'])
        themes[name] = theme(name, tokens, data['roleTones'][variant['base']])

    for name, values in themes.items():
        for rule in data['contrast']:
            if not isinstance(rule, list) or len(rule) != 3 or type(rule[2]) not in (int, float):
                raise ValueError('contrast rules are [foreground, background, minimum]')
            foreground, background, minimum = rule
            for role in roles if 'role.' in foreground + background else ('',):
                first = foreground.replace('role', role, 1) if foreground.startswith('role.') else foreground
                second = background.replace('role', role, 1) if background.startswith('role.') else background
                if first not in values or second not in values:
                    raise ValueError(f'contrast rule names unknown colour {first} or {second}')
                ratio = contrast(values[first].hex, values[second].hex)
                if ratio < minimum:
                    raise ValueError(f'{name}: {first} on {second} is {ratio:.2f}:1, below {minimum}:1')
    return {'data': data, 'themes': themes}


def flat(name: str) -> str:
    """serverStrong for the role tone server.strong, the token name otherwise."""
    role, _, tone = name.partition('.')
    return role + tone[0].upper() + tone[1:] if tone else name


def render_qml(palette: dict) -> str:
    lines = [f'// {BANNER}', '// Theme.qml maps these onto the names the pages use.', '.pragma library', '']
    for name in ('light', 'dark'):
        lines.append(f'var {name} = {{')
        lines.extend(f'    {flat(key)}: "{colour.hex.lower()}",' for key, colour in palette['themes'][name].items())
        lines.append('};')
        lines.append('')
    return '\n'.join(lines)


def render_kotlin(palette: dict) -> str:
    roles = list(palette['data']['roles'])
    lines = [f'// {BANNER}', 'package com.fixcraft.yume.ui.theme', '',
             'import androidx.compose.material3.ColorScheme',
             'import androidx.compose.material3.darkColorScheme',
             'import androidx.compose.material3.lightColorScheme',
             'import androidx.compose.ui.graphics.Color', '',
             '/**',
             ' * A role colour of figures and states: a mid tone, a strong ink, a soft container,',
             ' * the text on that container, and a saturated dot for small marks on any ground.',
             ' */',
             'internal class YumeRole(val mid: Color, val strong: Color, val soft: Color, val onSoft: Color, val dot: Color)', '',
             '/** One theme: the Material scheme and the colours Material has no role for. */',
             'internal class YumePalette(',
             '    val scheme: ColorScheme,',
             '    val button: Color,',
             '    val buttonInk: Color,',
             '    val buttonPressed: Color,',
             '    val track: Color,']
    lines += [f'    val {role}: YumeRole,' for role in roles]
    lines += [')', '']

    def colour(value: Colour) -> str:
        return f'Color(0xFF{value.hex[1:]})'

    for name, values in palette['themes'].items():
        builder = 'lightColorScheme' if name == 'light' else 'darkColorScheme'
        lines.append(f'internal val Yume{name[0].upper() + name[1:]} = YumePalette(')
        lines.append(f'    scheme = {builder}(')
        for role, token in MATERIAL.items():
            value = Colour(token, 0, role) if token.startswith('#') else values[token]
            lines.append(f'        {role} = {colour(value)},')
        lines.append('    ),')
        for token in ('button', 'buttonInk', 'buttonPressed', 'track'):
            lines.append(f'    {token} = {colour(values[token])},')
        for role in roles:
            tones = ', '.join(colour(values[f'{role}.{tone}']) for tone in TONES)
            lines.append(f'    {role} = YumeRole({tones}),')
        lines.append(')')
        lines.append('')
    return '\n'.join(lines)


def render_cpp(palette: dict) -> str:
    light = palette['themes']['light']
    lines = [f'// {BANNER}', '#pragma once', '', 'namespace yume::gui::palette {', '',
             '// The mark\'s two gradient stops, as it shows over white, as 0xRRGGBB.']
    for token, name in (('logoFrom', 'kLogoFrom'), ('logoTo', 'kLogoTo')):
        lines.append(f'inline constexpr unsigned {name} = 0x{light[token].hex[1:].lower()};')
    lines += ['', '// The tray\'s state dots: saturated role tones that read on light and dark',
              '// panels, and the strong outline grey at rest.']
    for token, name in (('outside.dot', 'kDotGood'), ('disguise.dot', 'kDotBusy'),
                        ('refused.dot', 'kDotBad'), ('lineStrong', 'kDotRest')):
        lines.append(f'inline constexpr unsigned {name} = 0x{light[token].hex[1:].lower()};')
    lines += ['', '}  // namespace yume::gui::palette', '']
    return '\n'.join(lines)


def mark_path(root: Path) -> str:
    match = re.search(r' d="([^"]+)"', (root / MARK_SOURCE).read_text(encoding='utf-8'))
    if match is None:
        raise ValueError(f'{MARK_SOURCE}: no path')
    return match.group(1)


def render_web_mark(palette: dict, path: str) -> str:
    light = palette['themes']['light']
    return '\n'.join([
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">',
        f'  <!-- {BANNER} -->',
        '  <defs>',
        '    <linearGradient id="mark" gradientUnits="userSpaceOnUse" x1="145.1" y1="251.9" x2="125.8" y2="22">',
        f'      <stop offset="0" stop-color="{light["logoFrom"].hex.lower()}"/>',
        f'      <stop offset="1" stop-color="{light["logoTo"].hex.lower()}"/>',
        '    </linearGradient>',
        '  </defs>',
        f'  <path fill="url(#mark)" d="{path}"/>',
        '</svg>', ''])


def render_readme_banner(palette: dict, root: Path, path: str) -> str:
    """Keep the hand-drawn mark and layout separate from generated colours."""
    values = {'mark_path': path}
    for theme in THEMES:
        values.update({f'{theme}_{name}': colour.hex.lower()
                       for name, colour in palette['themes'][theme].items()})
    template = Template((root / README_BANNER_SOURCE).read_text(encoding='utf-8'))
    return template.substitute(values)


def render_android_mark(palette: dict, current: str) -> str:
    light = palette['themes']['light']
    stops = re.findall(r'<item android:offset="[01]" android:color="#[0-9A-F]{6,8}"/>', current)
    if len(stops) != 2:
        raise ValueError(f'{ANDROID_MARK_OUTPUT}: expected two gradient stops')
    result = current
    for offset, token in (('0', 'logoFrom'), ('1', 'logoTo')):
        result = re.sub(rf'<item android:offset="{offset}" android:color="#[0-9A-F]{{6,8}}"/>',
                        f'<item android:offset="{offset}" android:color="#FF{light[token].hex[1:]}"/>', result)
    return result


def render_android_tile(palette: dict) -> str:
    return '\n'.join([
        '<?xml version="1.0" encoding="utf-8"?>',
        f'<!-- {BANNER} -->',
        '<resources>',
        f'    <color name="ic_launcher_background">{palette["themes"]["light"]["surface"].hex}</color>',
        '</resources>', ''])


WEB_REGIONS = ('light', 'dark-source', 'dark')


def render_web(palette: dict, current: str) -> str:
    themes = palette['themes']
    roles = list(palette['data']['roles'])
    names = [(css, token) for css, token in WEB]
    names += [(f'role-{role}{suffix}', f'{role}.{tone}') for role in roles for suffix, tone in WEB_TONES]
    regions = {
        'light': [f'  --color-{css}: {themes["light"][token].css()};' for css, token in names]
                 + [f'  --color-{css}: {value};' for css, value in WEB_REFERENCES],
        'dark-source': [f'  --dark-{css}: {themes["dark"][token].css()};' for css, token in names],
        'dark': [f'  --color-{css}: var(--dark-{css});' for css, _token in names],
    }
    result = current
    for region in WEB_REGIONS:
        start = f'  /* palette:{region} {BANNER} */\n'
        end = '  /* palette:end */\n'
        pattern = re.compile(re.escape(start) + r'.*?' + re.escape(end), re.S)
        if len(pattern.findall(result)) != 1:
            raise ValueError(f'{WEB_OUTPUT}: needs exactly one palette:{region} region')
        result = pattern.sub(lambda _m: start + '\n'.join(regions[region]) + '\n' + end, result)
    return result


def render(palette: dict, root: Path, android_root: Path | None = None) -> dict[Path, str]:
    if palette['themes']['light']['logoFrom'].hex != palette['themes']['dark']['logoFrom'].hex or \
            palette['themes']['light']['logoTo'].hex != palette['themes']['dark']['logoTo'].hex:
        raise ValueError('the mark keeps one pair of colours in every theme')
    path = mark_path(root)
    outputs = {root / QML_OUTPUT: render_qml(palette), root / CPP_OUTPUT: render_cpp(palette),
               root / WEB_OUTPUT: render_web(palette, (root / WEB_OUTPUT).read_text(encoding='utf-8')),
               root / WEB_MARK_OUTPUT: render_web_mark(palette, path),
               root / README_BANNER_OUTPUT: render_readme_banner(palette, root, path)}
    if android_root is not None:
        outputs[android_root / ANDROID_OUTPUT] = render_kotlin(palette)
        outputs[android_root / ANDROID_MARK_OUTPUT] = render_android_mark(
            palette, (android_root / ANDROID_MARK_OUTPUT).read_text(encoding='utf-8'))
        outputs[android_root / ANDROID_TILE_OUTPUT] = render_android_tile(palette)
    return outputs


def generate(outputs: dict[Path, str], *, check: bool = False) -> list[Path]:
    changed = [path for path, content in outputs.items()
               if not path.is_file() or path.read_text(encoding='utf-8') != content]
    if not check:
        for path in changed:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(outputs[path], encoding='utf-8')
    return changed


def report(palette: dict) -> str:
    """Each theme's colours with the contrast of the main text pairs."""
    lines = []
    for name, values in palette['themes'].items():
        lines.append(f'{name}:')
        for key, value in values.items():
            on_surface = contrast(value.hex, values['surface'].hex)
            lines.append(f'  {key:20} {value.hex}  {value.css():28} {on_surface:5.2f}:1 on surface')
    return '\n'.join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=('validate', 'generate', 'report'))
    parser.add_argument('--check', action='store_true', help='fail on drift without writing')
    parser.add_argument('--android-root', type=Path, help='separate Android checkout to generate/check')
    args = parser.parse_args()
    if args.check and args.command != 'generate':
        parser.error('--check requires generate')
    try:
        palette = load()
        if args.command == 'report':
            print(report(palette))
            return 0
        if args.android_root is not None and not (args.android_root / 'app').is_dir():
            raise ValueError('--android-root must contain app/')
        if args.command == 'generate':
            changed = generate(render(palette, ROOT, args.android_root), check=args.check)
            if args.check and changed:
                for path in changed:
                    print(f'palette drift: {path}', file=sys.stderr)
                return 1
        print('palette: valid' + ('; Android not requested' if args.android_root is None else '; Android included'))
        return 0
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f'palette: {error}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
