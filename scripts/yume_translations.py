#!/usr/bin/env python3
"""Validate and generate YUME's shared desktop/Android message catalog.

The JSON catalog is the only hand-edited translation source. Qt TS and Kotlin
maps are generated views; generated files carry a banner and are reproducible.

Maintained languages must translate every message. Community languages, listed
in `community_languages`, are human-reviewed translations that fall back to
English per message, are listed only above the coverage floor, and never
translate a message flagged `maintainer_review`. Every language, maintained or
community, names its own name and who translated it.
"""
from __future__ import annotations
import argparse, html, json, re, sys, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "translations/catalog.json"
ID_RE = re.compile(r"^[a-z][a-z0-9]*(?:\.[a-z0-9]+)*$")
TAG_RE = re.compile(r"</?[A-Za-z][^>]*>")
TOKEN_RE = re.compile(r"%(?:\d+\$)?[-+# 0,(]*\d*(?:\.\d+)?[sdif]|%\d+")
DIRECT_QT_RE = re.compile(r"\bqsTr\s*\(|(?<![A-Za-z0-9_])tr\s*\(")
LANGS = ("ru", "ja", "uk")
# A catalog language is a lowercase ISO 639 code, with a script subtag where
# the language is written in more than one script. No region: zh-CN and zh-SG
# are both zh-Hans.
LANGUAGE_TAG_RE = re.compile(r"^[a-z]{2,3}(?:-[A-Z][a-z]{3})?$")
# Languages whose readers need one script, so one catalog cannot serve them
# all and the tag must say which it is.
SCRIPT_REQUIRED = {"zh": ("Hans", "Hant")}
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
CREDIT_KINDS = ("person", "studio")
DEFAULT_COMMUNITY_COVERAGE = 0.8
GENERATED = "GENERATED by scripts/yume_translations.py; do not edit."
# Letters by script, and the scripts each maintained language is written in.
# A letter of any other listed script is text pasted from the wrong language.
SCRIPT_LETTERS = {
    "Cyrillic": re.compile(r"[\u0400-\u052f]"),
    "kana": re.compile(r"[\u3040-\u30ff]"),
    "Han": re.compile(r"[\u3400-\u4dbf\u4e00-\u9fff]"),
}
LANGUAGE_SCRIPTS = {"ru": ("Cyrillic",), "uk": ("Cyrillic",), "ja": ("kana", "Han"),
                    "zh-Hans": ("Han",)}

def tag_errors(where: str, tag) -> list[str]:
    """The catalog's own rules for a language tag, maintained or community."""
    if not isinstance(tag, str) or not LANGUAGE_TAG_RE.fullmatch(tag) or tag == "en":
        return [f"{where}: must be a lowercase language code with an optional script subtag "
                "(ru, zh-Hans), and not English"]
    language, _, script = tag.partition("-")
    scripts = SCRIPT_REQUIRED.get(language)
    if scripts and script not in scripts:
        return [f"{where}: {language} must name its script, one of " + ", ".join(f"{language}-{s}" for s in scripts)]
    return []

def language_symbol(tag: str) -> str:
    """The Kotlin name part for a tag: ru -> Ru, zh-Hans -> ZhHans."""
    return "".join(part[:1].upper() + part[1:].lower() for part in tag.split("-"))

def catalog_languages(data: dict) -> tuple[str, ...]:
    value = data.get("maintained_languages", LANGS)
    return tuple(value) if isinstance(value, list) else LANGS

def community_languages(data: dict) -> dict:
    value = data.get("community_languages", {})
    return value if isinstance(value, dict) else {}

def qt_languages(data: dict) -> tuple[str, ...]:
    return ("en",) + catalog_languages(data) + tuple(community_languages(data))

def community_floor(data: dict) -> float:
    value = data.get("policy", {}).get("community_minimum_coverage", DEFAULT_COMMUNITY_COVERAGE)
    return value if isinstance(value, (int, float)) and not isinstance(value, bool) else DEFAULT_COMMUNITY_COVERAGE

def translated(message: dict, lang: str) -> str | None:
    value = message.get("translations", {}).get(lang) if isinstance(message.get("translations"), dict) else None
    return value if isinstance(value, str) and value.strip() else None

def community_coverage(data: dict, lang: str) -> float:
    """Share of the messages a community language may translate that it does.

    A language-neutral message is already right in English."""
    eligible = [m for m in data.get("messages", []) if not m.get("maintainer_review")]
    if not eligible:
        return 1.0
    done = sum(1 for m in eligible if m.get("language_neutral") or translated(m, lang))
    return done / len(eligible)

def credit_errors(where: str, credits) -> list[str]:
    errors = []
    if not isinstance(credits, list) or not credits:
        return [f"{where}.credits: at least one translator or studio required"]
    for index, credit in enumerate(credits):
        at = f"{where}.credits[{index}]"
        if not isinstance(credit, dict) or set(credit) - {"name", "kind", "url"}:
            errors.append(f"{at}: object with name, kind and optional url required"); continue
        if not isinstance(credit.get("name"), str) or not credit["name"].strip():
            errors.append(f"{at}.name: required")
        if credit.get("kind") not in CREDIT_KINDS:
            errors.append(f"{at}.kind: one of {', '.join(CREDIT_KINDS)}")
        url = credit.get("url")
        if url is not None and (not isinstance(url, str) or not re.fullmatch(r"https://[^\s<>\"]+", url)):
            errors.append(f"{at}.url: an https URL")
    return errors

def maintained_details(data: dict) -> dict:
    value = data.get("maintained_language_details", {})
    return value if isinstance(value, dict) else {}

def maintained_errors(data: dict) -> list[str]:
    errors = []
    details = data.get("maintained_language_details")
    if not isinstance(details, dict):
        return ["maintained_language_details must name and credit every maintained language"]
    if set(details) != set(catalog_languages(data)):
        errors.append("maintained_language_details must cover exactly the maintained languages")
    for tag in catalog_languages(data):
        errors += tag_errors(f"maintained_languages.{tag}", tag)
    for tag, entry in details.items():
        where = f"maintained_language_details.{tag}"
        if not isinstance(entry, dict) or set(entry) - {"name", "credits"}:
            errors.append(f"{where}: object with name and credits required"); continue
        if not isinstance(entry.get("name"), str) or not entry["name"].strip():
            errors.append(f"{where}.name: the language's own name is required")
        errors += credit_errors(where, entry.get("credits"))
    return errors

def community_errors(data: dict) -> list[str]:
    errors = []
    languages = data.get("community_languages", {})
    if not isinstance(languages, dict):
        return ["community_languages must be an object keyed by language code"]
    floor = data.get("policy", {}).get("community_minimum_coverage", DEFAULT_COMMUNITY_COVERAGE)
    if isinstance(floor, bool) or not isinstance(floor, (int, float)) or not 0 < floor <= 1:
        errors.append("policy.community_minimum_coverage must be a number above 0 and at most 1")
    for tag, entry in languages.items():
        where = f"community_languages.{tag}"
        errors += tag_errors(where, tag)
        if tag in catalog_languages(data):
            errors.append(f"{where}: is already a maintained language")
        if not isinstance(entry, dict):
            errors.append(f"{where}: object required"); continue
        unknown = set(entry) - {"name", "since", "credits"}
        if unknown:
            errors.append(f"{where}: unknown keys {sorted(unknown)}")
        if not isinstance(entry.get("name"), str) or not entry["name"].strip():
            errors.append(f"{where}.name: the language's own name is required")
        if not isinstance(entry.get("since"), str) or not DATE_RE.fullmatch(entry["since"]):
            errors.append(f"{where}.since: YYYY-MM-DD required")
        errors += credit_errors(where, entry.get("credits"))
        if isinstance(floor, (int, float)) and not isinstance(floor, bool) and community_coverage(data, tag) < floor:
            errors.append(f"{where}: covers {community_coverage(data, tag):.0%} of its messages, below the {floor:.0%} floor")
    return errors

def load(path: Path = CATALOG) -> dict:
    try: data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as e: raise SystemExit(f"catalog: {e}")
    return data

def runtime_source_errors(root: Path = ROOT) -> list[str]:
    """Reject source-text lookups so the catalog ID is the runtime identity."""
    errors = []
    paths = list((root / "src/gui").glob("**/*.cpp"))
    paths += list((root / "src/gui").glob("**/*.hpp"))
    paths += list((root / "src/gui").glob("**/*.qml"))
    paths += list((root / "src/gui").glob("**/*.js"))
    for path in sorted(paths):
        text = path.read_text(encoding="utf-8")
        for match in DIRECT_QT_RE.finditer(text):
            line = text.count("\n", 0, match.start()) + 1
            errors.append(f"{path.relative_to(root)}:{line}: use qsTrId/qtTrId with a catalog ID")
    return errors

def translation_errors(where: str, lang: str, value: str, message: dict, actual: list, data: dict) -> list[str]:
    errors = []
    if sorted(TOKEN_RE.findall(value)) != sorted(actual): errors.append(f"{where}: {lang} placeholders {TOKEN_RE.findall(value)!r} != {actual!r}")
    if value.count("<") != value.count(">") or TAG_RE.findall(value) != TAG_RE.findall(message.get("source", "")):
        errors.append(f"{where}: {lang} malformed or changed markup")
    for term in data.get("terminology", []):
        if term in message.get("source", "") and term not in value:
            errors.append(f"{where}: {lang} drops protected term {term}")
    if value == message.get("source") and not message.get("language_neutral"):
        errors.append(f"{where}: {lang} is an English fallback; mark language_neutral only for intentional terms")
    own = LANGUAGE_SCRIPTS.get(lang)
    for script, letters in SCRIPT_LETTERS.items():
        if own is not None and script not in own and (found := letters.search(value)):
            errors.append(f"{where}: {lang} contains the {script} letter {found.group()!r}; {lang} is not written in {script}")
    return errors

def validate(data: dict) -> list[str]:
    errors=[]; messages=data.get("messages")
    if data.get("version") != 1 or not isinstance(messages,list): return ["catalog must have version 1 and a messages array"]
    errors += maintained_errors(data)
    errors += community_errors(data)
    community = community_languages(data)
    known_languages = set(catalog_languages(data)) | set(community)
    ids=set(); sources=set()
    for i,m in enumerate(messages):
        where=f"messages[{i}]"
        mid=m.get("id")
        if not isinstance(mid,str) or not ID_RE.fullmatch(mid): errors.append(f"{where}: invalid id {mid!r}")
        elif mid in ids: errors.append(f"{where}: duplicate id {mid}")
        ids.add(mid)
        source=m.get("source")
        if isinstance(source,str) and source in sources: errors.append(f"{where}: duplicate source text; assign one stable ID")
        sources.add(source)
        for key in ("source","context","owner","notes"):
            if not isinstance(m.get(key),str) or not m[key].strip(): errors.append(f"{where}.{key}: required non-empty string")
        requirements=m.get("requirements",{})
        expected=requirements.get("placeholders",[])
        limit=requirements.get("character_limit")
        if limit is not None and (not isinstance(limit,int) or limit < 1): errors.append(f"{where}: character_limit must be a positive integer")
        if isinstance(limit,int) and len(m.get("source","")) > limit: errors.append(f"{where}: source exceeds character_limit")
        actual=TOKEN_RE.findall(m.get("source",""))
        if expected != actual: errors.append(f"{where}: requirements.placeholders {expected!r} != source {actual!r}")
        if "maintainer_review" in m and not isinstance(m["maintainer_review"], bool):
            errors.append(f"{where}.maintainer_review: true or false")
        translations=m.get("translations")
        if not isinstance(translations,dict): errors.append(f"{where}.translations: object required"); continue
        for lang in sorted(set(translations) - known_languages):
            errors.append(f"{where}: {lang} is neither a maintained nor a community language")
        for lang in catalog_languages(data):
            value=translations.get(lang)
            if not isinstance(value,str) or not value.strip(): errors.append(f"{where}: missing {lang} translation")
            else: errors += translation_errors(where, lang, value, m, actual, data)
        for lang in community:
            if lang not in translations: continue
            value = translations[lang]
            if not isinstance(value, str) or not value.strip():
                errors.append(f"{where}: {lang} translation must be text; leave it out to show English")
            elif m.get("maintainer_review"):
                errors.append(f"{where}: {lang} cannot translate maintainer_review text; it stays English")
            else: errors += translation_errors(where, lang, value, m, actual, data)
    return errors

def kotlin(s: str) -> str:
    return json.dumps(s,ensure_ascii=False).replace("$", "\\$")

def message_symbol(mid: str) -> str:
    return mid.replace(".", "_").upper()


def android_source_errors(data: dict, android_root: Path) -> list[str]:
    path = android_root / "app/src/main/java/com/fixcraft/yume/i18n/AppStrings.kt"
    text = path.read_text(encoding="utf-8")
    known = {message_symbol(m["id"]) for m in data["messages"]}
    used = set(re.findall(r"MessageId\.([A-Z0-9_]+)", text))
    errors = [f"unknown Android message ID accessor: {name}" for name in sorted(used - known)]
    if re.search(r'\bt\(\s*"', text) or "sourceToId" in text:
        errors.append("AppStrings must use typed message IDs, not English lookup keys")
    return errors


def android_languages(data: dict) -> tuple[str, ...]:
    return catalog_languages(data) + tuple(community_languages(data))

def generate_android(data: dict, out: Path) -> None:
    out.mkdir(parents=True,exist_ok=True)
    maps = out / "translations"
    maps.mkdir(parents=True,exist_ok=True)
    for lang in android_languages(data):
        lines=["// GENERATED by scripts/yume_translations.py; do not edit.","package com.fixcraft.yume.i18n.translations","","import com.fixcraft.yume.i18n.LanguageBundle","","internal object Language%s : LanguageBundle {" % language_symbol(lang),f'    override val localeTag: String = "{lang}"',"    override val translations: Map<String, String> = linkedMapOf("]
        # A community language lists only what it translates, so the rest
        # falls back to English.
        for m in data["messages"]:
            if translated(m, lang): lines.append(f"        {kotlin(m['id'])} to {kotlin(m['translations'][lang])},")
        lines += ["    )","}",""]
        (maps/f"Language{language_symbol(lang)}.kt").write_text("\n".join(lines),encoding="utf-8")
    community = community_languages(data)

    def credit_list(credits: list) -> str:
        return "listOf(" + ", ".join(
            f"TranslationCredit({kotlin(c['name'])}, TranslationCredit.Kind.{c['kind'].title()}, {kotlin(c['url']) if c.get('url') else 'null'})"
            for c in credits) + ")"

    lines = [f"// {GENERATED}", "package com.fixcraft.yume.i18n", ""]
    lines += [f"import com.fixcraft.yume.i18n.translations.Language{language_symbol(lang)}" for lang in community]
    if community: lines.append("")
    lines += ["/** Who translated each maintained language, from the shared catalog. */",
              "internal object MaintainedLanguageCredits {", "    val credits: Map<String, List<TranslationCredit>> = mapOf("]
    for lang, entry in maintained_details(data).items():
        lines.append(f"        {kotlin(lang)} to {credit_list(entry['credits'])},")
    lines += ["    )", "}", "",
              "/** Human community translations from the shared catalog, with their credits. */",
              "internal object CommunityLanguages {", "    val all: List<CommunityLanguage> = listOf("]
    for lang, entry in community.items():
        percent = int(community_coverage(data, lang) * 100)
        lines.append(f"        CommunityLanguage({kotlin(lang)}, {kotlin(entry['name'])}, {percent}, {credit_list(entry['credits'])}),")
    lines += ["    )", "    val bundles: Map<String, LanguageBundle> = mapOf("]
    lines += [f"        {kotlin(lang)} to Language{language_symbol(lang)}," for lang in community]
    lines += ["    )", "}", ""]
    (out/"TranslationCredits.kt").write_text("\n".join(lines),encoding="utf-8")
    lines=["// GENERATED by scripts/yume_translations.py; do not edit.","package com.fixcraft.yume.i18n","","/** Stable IDs and source text for the shared catalog. */","internal object TranslationCatalog {","    val sourceToId: Map<String, String> = linkedMapOf("]
    for m in data["messages"]: lines.append(f"        {kotlin(m['source'])} to {kotlin(m['id'])},")
    lines += ["    )", "    val idToSource: Map<String, String> = linkedMapOf("]
    for m in data["messages"]: lines.append(f"        {kotlin(m['id'])} to {kotlin(m['source'])},")
    lines += ["    )", "}", ""]
    lines += ["/** Generated message identities, independent of English copy. */",
              "enum class MessageId(val id: String, val source: String) {"]
    for m in data["messages"]:
        lines.append(f"    {message_symbol(m['id'])}({kotlin(m['id'])}, {kotlin(m['source'])}),")
    lines += ["}", ""]
    (out/"TranslationCatalog.kt").write_text("\n".join(lines),encoding="utf-8")

def qt_text(value: str) -> str:
    """Adapt printf/Kotlin placeholders to Qt's numbered %1 form."""
    index = 0
    def replace(match: re.Match[str]) -> str:
        nonlocal index
        token = match.group(0)
        if token.startswith("%") and token[1:].isdigit():
            return token
        numbered = re.fullmatch(r"%(\d+)\$[sdif]", token)
        if numbered:
            return "%" + numbered.group(1)
        index += 1
        return "%" + str(index)
    return re.sub(r"%(?:\d+\$)?[-+# 0,(]*\d*(?:\.\d+)?[sdif]|%\d+", replace, value)

def generate_qt(data: dict, out: Path) -> None:
    out.mkdir(parents=True,exist_ok=True)
    for lang in qt_languages(data):
        lines=['<?xml version="1.0" encoding="utf-8"?>','<!DOCTYPE TS>','<!-- GENERATED by scripts/yume_translations.py; do not edit. -->',f'<TS version="2.1" language="{lang.replace("-", "_")}">']
        # ID lookups use the empty context and source, matching the TS shape
        # emitted by lupdate for qtTrId/qsTrId. Keep richer metadata in an
        # extra comment for Linguist users without changing the lookup key.
        lines += ["  <context>", "    <name></name>"]
        for m in data["messages"]:
            # A community language leaves untranslated IDs to the English
            # catalog installed beneath it.
            if lang in community_languages(data) and not translated(m, lang): continue
            text = m["source"] if lang == "en" else m["translations"][lang]
            tr=html.escape(qt_text(text),quote=False)
            note = html.escape(
                f"source: {m['source']}; context: {m['context']}; "
                f"owner: {m['owner']}; {m['notes']}",
                quote=False)
            lines += [f"    <message id=\"{m['id']}\">",f"      <location filename=\"catalog:{m['id']}\" line=\"1\"/>","      <source></source>",f"      <extracomment>{note}</extracomment>",f"      <translation>{tr}</translation>","    </message>"]
        lines += ["  </context>", "</TS>",""]
        (out/f"yume_{lang}.ts").write_text("\n".join(lines),encoding="utf-8")
    # Maintained languages first, then community ones, each with its credits.
    languages = [{"tag": lang, "name": entry["name"], "group": "maintained", "coverage": 100,
                  "credits": entry["credits"]} for lang, entry in maintained_details(data).items()]
    languages += [{"tag": lang, "name": entry["name"], "group": "community",
                   "coverage": int(community_coverage(data, lang) * 100),
                   "credits": entry["credits"]} for lang, entry in community_languages(data).items()]
    (out/"translation_credits.json").write_text(json.dumps({"generated": GENERATED, "languages": languages},
                                                           ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

def generated_pairs(data: dict, tmp: Path, android_root: Path | None) -> list[tuple[Path, Path]]:
    """(fresh, checked-in) pairs for every generated view, plus any checked-in
    view that no longer has a language (paired with a missing fresh file)."""
    desktop = ROOT / "src/gui/translations"
    pairs = [(tmp/"qt"/f"yume_{l}.ts", desktop/f"yume_{l}.ts") for l in qt_languages(data)]
    pairs.append((tmp/"qt"/"translation_credits.json", desktop/"translation_credits.json"))
    pairs += [(tmp/"qt"/p.name, p) for p in desktop.glob("yume_*.ts") if p.stem[5:] not in qt_languages(data)]
    if android_root:
        kotlin_root = android_root/"app/src/main/java/com/fixcraft/yume/i18n"
        pairs += [(tmp/"android/translations"/f"Language{language_symbol(l)}.kt", kotlin_root/"translations"/f"Language{language_symbol(l)}.kt") for l in android_languages(data)]
        pairs += [(tmp/"android"/name, kotlin_root/name) for name in ("TranslationCatalog.kt", "TranslationCredits.kt")]
        known = {f"Language{language_symbol(l)}.kt" for l in android_languages(data)}
        pairs += [(tmp/"android/translations"/p.name, p) for p in (kotlin_root/"translations").glob("Language*.kt") if p.name not in known]
    return pairs

def add(args):
    data=load(); errs=validate(data)
    if args.id in {m['id'] for m in data['messages']}: raise SystemExit(f"add: duplicate id {args.id}")
    placeholders=TOKEN_RE.findall(args.source)
    translations={l:"" for l in data['maintained_languages']}
    data['messages'].append({'id':args.id,'source':args.source,'context':args.context,'owner':args.owner,'notes':args.notes,'requirements':{'placeholders':placeholders},'translations':translations})
    CATALOG.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')
    print(f"added {args.id}; fill translations, then run validate")

def main():
    p=argparse.ArgumentParser(); sub=p.add_subparsers(dest='command',required=True)
    v=sub.add_parser('validate'); v.add_argument('--catalog',type=Path,default=CATALOG)
    a=sub.add_parser('add'); a.add_argument('id'); a.add_argument('source'); a.add_argument('--context',required=True); a.add_argument('--owner',required=True); a.add_argument('--notes',required=True)
    r=sub.add_parser('rename'); r.add_argument('old'); r.add_argument('new')
    g=sub.add_parser('generate'); g.add_argument('--android-root',type=Path); g.add_argument('--check',action='store_true')
    args=p.parse_args(); data=load()
    if args.command=='validate':
        errors=validate(load(args.catalog));
        if args.catalog == CATALOG:
            errors += runtime_source_errors()
        if errors: print("\n".join(errors),file=sys.stderr); return 1
        checked = load(args.catalog)
        community = [f"{l} {community_coverage(checked, l):.0%}" for l in community_languages(checked)]
        print(f"valid: {len(checked['messages'])} messages; maintained languages: {', '.join(catalog_languages(checked))}; "
              f"community languages: {', '.join(community) or 'none'}"); return 0
    if args.command=='add': add(args); return 0
    if args.command=='rename':
        if any(m['id']==args.new for m in data['messages']): raise SystemExit(f"rename: duplicate id {args.new}")
        for m in data['messages']:
            if m['id']==args.old: m['id']=args.new; break
        else: raise SystemExit(f"rename: unknown id {args.old}")
        CATALOG.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n'); print(f"renamed {args.old} -> {args.new}"); return 0
    errors=validate(data)
    if errors: print("\n".join(errors),file=sys.stderr); return 1
    if args.check:
        # compare against temporary deterministic output without touching targets
        with tempfile.TemporaryDirectory() as t:
            generate_qt(data,Path(t)/"qt"); generate_android(data,Path(t)/"android")
            pairs=generated_pairs(data, Path(t), args.android_root)
            stale=[str(dst) for src,dst in pairs if not src.is_file() or not dst.is_file() or src.read_bytes()!=dst.read_bytes()]
            if stale:
                print("generated output is stale (regenerate; source IDs are canonical):\n"+"\n".join(stale),file=sys.stderr); return 1
    else:
        generate_qt(data,ROOT/"src/gui/translations")
        if args.android_root: generate_android(data,args.android_root/"app/src/main/java/com/fixcraft/yume/i18n")
        # A language that left the catalog leaves no generated view behind.
        with tempfile.TemporaryDirectory() as t:
            generate_qt(data,Path(t)/"qt"); generate_android(data,Path(t)/"android")
            for fresh, view in generated_pairs(data, Path(t), args.android_root):
                if not fresh.exists() and view.is_file() and GENERATED in view.read_text(encoding="utf-8"):
                    view.unlink()
    print(f"generated {len(data['messages'])} messages")
    return 0
if __name__=='__main__': raise SystemExit(main())
